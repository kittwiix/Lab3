# -*- coding: utf-8 -*-
"""Собственные исключения приложения.

Свои классы нужны, чтобы интерфейс мог отличить ошибку пользователя
(неверная сумма, пустое название) от сбоя базы или файловой системы.
Все наследники TrackerError, поэтому в окне и на веб-странице достаточно
одного except TrackerError — и пользователь увидит нормальный текст,
а не трассировку Python.
"""


class TrackerError(Exception):
    """Общая ошибка трекера, от неё наследуется всё остальное."""


class ValidationError(TrackerError):
    """Некорректные данные расхода: сумма, дата, название, категория."""


class RepositoryError(TrackerError):
    """Ошибка при работе с базой данных."""


class ExpenseNotFound(TrackerError):
    """Расход не найден — например, его уже удалили в другом окне."""


class DuplicateExpense(TrackerError):
    """Такой расход уже добавлен: совпали название, дата и сумма."""


class ExportError(TrackerError):
    """Не удалось сохранить файл: нет прав или папка недоступна."""
